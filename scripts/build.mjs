// Regenerates the generated parts of the site from data/nodes.json:
// - the index table in index.html (between the index:start and index:end markers), so the
//   map page lists every work without JS; PDF project titles link to their pages
// - work/<slug>/index.html for the three PDF projects, from the same markup as the full
//   page over the map (pageHTML in js/open/content.js), readable with JS off
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { root } from "./serve.mjs";
import { indexData, pageHTML, pageHref, hasPage, esc, icon, kindLabel, KIND_ICON } from "../js/open/content.js";

const data = JSON.parse(readFileSync(join(root, "data", "nodes.json"), "utf8"));
const ix = indexData(data);
const SITE = "https://bryliejw.github.io";

// Writes a file only when it changes; returns whether it did.
function put(file, text) {
  let old = null;
  try {
    old = readFileSync(file, "utf8");
  } catch {}
  if (old === text) return false;
  writeFileSync(file, text);
  return true;
}

// Index table
const file = join(root, "index.html");
const html = readFileSync(file, "utf8");
const LEVELS = [["L", "Projects"], ["M", "Extras"], ["S", "More work"]];
const ordered = LEVELS.flatMap(([size]) => data.works.filter((w) => w.size === size).sort((a, b) => (size === "S" ? (b.year ?? 0) - (a.year ?? 0) || a.title.localeCompare(b.title) : 0)));
const rows = ordered.map((w, i) => {
  const head = i === 0 || ordered[i - 1].size !== w.size ? `        <tr class="ix-grp"><th scope="rowgroup" colspan="5" class="mono-label">${LEVELS.find((l) => l[0] === w.size)[1]}</th></tr>\n` : "";
  const sub = w.sub ? `<span class="ix-sub">${esc(w.sub)}</span>` : "";
  const title = `<span class="ix-title">${esc(w.title)}</span>${sub}`;
  return (
    head +
    `        <tr data-id="${esc(w.id)}" data-kind="${w.kind}" data-level="${w.size}">` +
    `<td class="ix-i">${w.images[0] ? `<img src="/${esc(w.images[0].thumb ?? w.images[0].src)}" alt="" width="56" height="42" loading="lazy">` : ""}</td>` +
    `<td class="ix-n">${esc(w.n)}</td>` +
    `<td class="ix-t">${hasPage(w) ? `<a class="ix-open" href="${pageHref(w)}">${title}</a>` : title}</td>` +
    `<td class="ix-y">${w.year ?? ""}</td>` +
    `<td class="ix-k">${icon(KIND_ICON[w.kind])}${kindLabel(w)}</td></tr>`
  );
});
const table = [
  `    <table class="ix">`,
  `      <thead><tr><th scope="col"><span class="sr-only">Image</span></th><th scope="col">No.</th><th scope="col">Title</th><th scope="col">Year</th><th scope="col">Type</th></tr></thead>`,
  `      <tbody>`,
  ...rows,
  `      </tbody>`,
  `    </table>`,
].join("\n");
const re = /(<!-- index:start[^>]*-->\n)[\s\S]*?(\n<!-- index:end -->)/;
if (!re.test(html)) throw new Error("index.html: index:start / index:end markers not found");
const changed = put(file, html.replace(re, `$1${table}$2`));
console.log(`build: index table, ${rows.length} works${changed ? "" : " (unchanged)"}`);

// Work pages
const head = (w) => `<!doctype html>
<html lang="en-AU">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(w.title)} · Brylie Wilson</title>
${w.sub ? `<meta name="description" content="${esc(w.sub)}">\n` : ""}<link rel="canonical" href="${SITE}${pageHref(w)}">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Anybody:wdth,wght@50..150,300..900&family=Geist+Mono:wght@400..600&family=Instrument+Sans:ital,wdth,wght@0,75..100,400..700;1,75..100,400..700&display=swap">
<link rel="stylesheet" href="/css/tokens.css">
<link rel="stylesheet" href="/css/site.css">
</head>`;

for (const w of ix.projects) {
  const dir = join(root, "work", w.slug);
  mkdirSync(dir, { recursive: true });
  const doc = `${head(w)}
<body class="wp-doc">
<!-- Generated by scripts/build.mjs from data/nodes.json; do not edit. -->
<main>
${pageHTML(w, ix)}
</main>
</body>
</html>
`;
  const did = put(join(dir, "index.html"), doc);
  console.log(`build: ${pageHref(w)}${did ? "" : " (unchanged)"}`);
}
