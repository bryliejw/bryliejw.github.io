// Builds assets/icons.svg: one <symbol id="name"> per Lucide icon in the CLAUDE.md Icons table.
// Stroke width, cap and join are left to CSS (.ic) so the sprite stays at 1.75, square, miter.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const pkg = join(root, "node_modules", "lucide-static");

// Order follows the Icons table, row by row.
export const ICONS = [
  "frame", "share-2", "target",
  "search", "sliders-horizontal", "layers", "list", "shuffle",
  "plus", "minus", "scan", "info",
  "user", "file-down", "mail",
  "book-open", "flask-conical", "file", "briefcase",
  "compass", "package", "wrench", "hash", "heart",
  "panel-right-open", "maximize-2", "x", "arrow-left", "arrow-up-right", "arrow-right",
  "file-text", "image", "workflow", "waypoints",
  "rotate-ccw",
  "grip-horizontal", "pin-off", "chevron-down", "chevron-left", "chevron-right", "chevrons-left", "chevrons-right", "minimize-2", "images",
];

const version = JSON.parse(readFileSync(join(pkg, "package.json"), "utf8")).version;
// "--" is not allowed inside an XML comment, so the licence's rule lines are spaced out.
const licence = readFileSync(join(pkg, "LICENSE"), "utf8")
  .trim()
  .replace(/-{2,}/g, (m) => m.split("").join(" "));

const symbols = ICONS.map((name) => {
  const svg = readFileSync(join(pkg, "icons", `${name}.svg`), "utf8");
  const inner = svg
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/^[\s\S]*?<svg[^>]*>/, "")
    .replace(/<\/svg>[\s\S]*$/, "")
    .split("\n")
    .map((l) => l.trim())
    .filter(Boolean)
    .join("");
  return `<symbol id="${name}" viewBox="0 0 24 24" fill="none" stroke="currentColor">${inner}</symbol>`;
});

const out = `<!--
Generated by scripts/icons.mjs. Do not edit by hand; run npm run icons.
Icons from lucide-static v${version} (https://lucide.dev).

${licence}
-->
<svg xmlns="http://www.w3.org/2000/svg" style="display:none">
${symbols.join("\n")}
</svg>
`;

writeFileSync(join(root, "assets", "icons.svg"), out);
console.log(`assets/icons.svg: ${symbols.length} icons from lucide-static v${version}`);
